import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const input = path.resolve(process.argv[2] || path.join(root, 'inventory/vehicles.json'));
const payload = JSON.parse(fs.readFileSync(input, 'utf8'));
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'dist/inventory.js'), 'utf8'), context);
const normalized = context.window.VeloceInventory.normalize(payload);
const target = path.join(root, 'dist/data/vehicles.js');
const content = JSON.stringify(payload, null, 2).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
fs.mkdirSync(path.dirname(target), {recursive: true});
fs.writeFileSync(target + '.tmp', '// Generated by scripts/build-inventory.mjs. Edit inventory/vehicles.json.\nwindow.VELOCE_INVENTORY_DATA = ' + content + ';\n');
fs.renameSync(target + '.tmp', target);
console.log(`Inventory ready: ${normalized.vehicles.length} vehicles, demo=${normalized.isDemo}`);
